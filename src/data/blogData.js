export function getAllBlogPosts() {
  return [...BLOG_POSTS].sort((a, b) => new Date(b.publishedAt) - new Date(a.publishedAt));
}

export function getBlogPostBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();
  return BLOG_POSTS.find((post) => post.slug.toLowerCase() === cleanSlug) || null;
}

export function getRelatedPosts(currentSlug, limit = 3) {
  return BLOG_POSTS.filter((post) => post.slug !== currentSlug).slice(0, limit);
}

